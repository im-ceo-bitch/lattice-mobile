#!/usr/bin/env python3
"""Read-only, offline verifier for expected vs imported Cloudflare D1 SQL dumps.

Inputs are PRIVATE D1 exports. Never upload them to a public repository or chat.
This verifier does not create, delete or alter Cloudflare resources. It compares
post-filter source exports (generated by prepare.py) with target exports, and
checks that every table, field, record and FK survives with the same IDs.

Usage:
  python3 Backend/CloudflareMigration/verify_cutover.py expected.sql imported.sql

No personal data, row IDs, or row contents appear in stdout/stderr.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import sqlite3
import sys
from pathlib import Path


def open_snapshot(path: str) -> sqlite3.Connection:
    contents = Path(path).read_text(encoding='utf-8')
    upper = contents.upper()
    if 'ATTACH DATABASE' in upper or 'LOAD_EXTENSION' in upper:
        raise ValueError('SQL snapshot contains unsupported SQL operations')
    connection = sqlite3.connect(':memory:')
    connection.execute('PRAGMA foreign_keys=OFF')
    connection.executescript(contents)
    connection.row_factory = sqlite3.Row
    return connection


def quote(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'


def tables(db: sqlite3.Connection) -> set[str]:
    return {r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%'")}


def columns(db: sqlite3.Connection, table: str) -> list[tuple]:
    return [tuple(row) for row in db.execute(f'PRAGMA table_info({quote(table)})')]


def digest_table(db: sqlite3.Connection, table: str) -> tuple[int, str]:
    """Order-independent SHA256 over canonicalized SQL row values; never print data."""
    cursor = db.execute(f'SELECT * FROM {quote(table)}')
    rows = []
    for row in cursor:
        values = []
        for value in row:
            if isinstance(value, bytes):
                values.append({'blob_sha256': hashlib.sha256(value).hexdigest()})
            else:
                values.append(value)
        encoded = json.dumps(values, ensure_ascii=False, separators=(',', ':'), sort_keys=True).encode('utf-8')
        rows.append(hashlib.sha256(encoded).digest())
    hash_ctx = hashlib.sha256()
    for encoded in sorted(rows):
        hash_ctx.update(encoded)
    return len(rows), hash_ctx.hexdigest()


def verify(expected_path: str, actual_path: str) -> dict:
    expected, actual = open_snapshot(expected_path), open_snapshot(actual_path)
    expected_tables, actual_tables = tables(expected), tables(actual)
    # Expected dump is prepared by allowlisted non-hotel migration. Never allow
    # hotel catalog tables to sneak into the imported operational database.
    prohibited = {'hotels', 'hotel_rooms', 'hotel_images', 'hotel_price_cache', 'primary_hotels'}
    errors = []
    if not expected_tables:
        errors.append({'reason': 'empty_expected_schema'})
    for table in sorted(prohibited & actual_tables):
        errors.append({'table': table, 'reason': 'hotel_catalog_found'})
    for table in sorted(expected_tables - actual_tables):
        errors.append({'table': table, 'reason': 'missing_table'})
    # New migration tracking tables may legitimately exist on the destination;
    # never require the imported database to omit them.
    checked = 0
    rows = 0
    for table in sorted(expected_tables & actual_tables):
        if columns(expected, table) != columns(actual, table):
            errors.append({'table': table, 'reason': 'schema_drift'})
            continue
        e_count, e_digest = digest_table(expected, table)
        a_count, a_digest = digest_table(actual, table)
        rows += a_count
        checked += 1
        if e_count != a_count or e_digest != a_digest:
            errors.append({'table': table, 'reason': 'row_mismatch', 'expected_count': e_count, 'actual_count': a_count})
    for label, db in [('expected', expected), ('actual', actual)]:
        # SQLite foreign keys can legitimately refer to external hotel identities
        # in historical dumps; the filtered baseline should have been rewritten
        # by prepare.py. If it was not, stop rather than marking it safe.
        violations = list(db.execute('PRAGMA foreign_key_check'))
        if violations:
            errors.append({'scope': label, 'reason': 'foreign_key_violation', 'count': len(violations)})
    expected.close(); actual.close()
    return {'ok': not errors, 'tables_checked': checked, 'rows_checked': rows,
            'error_count': len(errors), 'issues': errors[:50],
            'note': 'D1 snapshot check only. R2 objects, Worker secrets, live writes and public API cutover are not checked.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('expected', help='Private filtered original D1 export')
    parser.add_argument('actual', help='Private new-account D1 export')
    args = parser.parse_args()
    try:
        result = verify(args.expected, args.actual)
    except (OSError, ValueError, sqlite3.DatabaseError) as error:
        print(json.dumps({'ok': False, 'error_type': type(error).__name__}), file=sys.stderr)
        sys.exit(2)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    sys.exit(0 if result['ok'] else 1)


if __name__ == '__main__':
    main()
